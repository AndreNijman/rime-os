#!/usr/bin/env python3
"""rime-rootfs-boot: the systemd generator that mounts /boot on every Rime OS NixOS machine (rime.rootfs;
nix/modules/rootfs.nix). Usage: rime-rootfs-boot NORMAL [EARLY LATE].

Where /boot is is a fact about the machine, not the build: one published toplevel boots a machine moved from bootc
and a fresh install alike. Both write it into /var/lib/rime/host.toml [boot]:

  layout = "bls"                                a FRESH install (installer/rime-install-nixos.sh): Rime's own ESP,
                                                FAT labelled ESPLABEL, at /boot
  layout = "custom-cfg"                         moved from bootc (`rime migrate start` writes it):
    with device = "UUID=..." fstype = "ext4"    the installer's LUKS layout, /boot its own partition
    without a device                            the plain layout, /boot a directory of the btrfs top level, bound from
                                                TOPMOUNT/boot (the top level is mounted there)

Both of those are REQUIRED by local-fs.target: the machine said where its /boot is. Anything else (no host.toml, one
that does not parse, layout "auto" or none) says nothing about the machine, and the boot must not hang on a guess (a
moved machine waiting for an ESP it does not have stopped in emergency mode on 2026-11-11). It gets a best guess that
local-fs.target only WANTS: Rime's ESP when /dev/disk/by-label/ESPLABEL exists when the generator runs (as rime-boot's
"auto" picks bls on a /boot without ostree), otherwise the bind, only if TOPMOUNT/boot is a directory. rime-boot reads
the same host.toml and refuses to write a menu it cannot place.

It writes NORMAL/boot.mount and hangs it from local-fs.target (and masks boot.automount there, so
systemd-gpt-auto-generator's automount does not cover it), once: when another generator already wrote boot.mount
(an fstab line), that one stays. When boot.mount is its own (an earlier, interrupted run), the link is made again. A
generator never fails the boot: every problem is said in the journal.
"""
import os
import re
import sys
import tomllib

HOST = os.environ.get("RIME_HOST_TOML", "/var/lib/rime/host.toml")
TOP = "@topMount@"
ESP_LABEL = "@espLabel@"
BY_LABEL = os.environ.get("RIME_DEV_BY_LABEL", "/dev/disk/by-label")  # tests point it elsewhere
HEADER = "# Generated by rime-rootfs-boot"
WHAT = re.compile(r"[^\s#]+")
FSTYPE = re.compile(r"[a-z0-9._]+")


def log(msg):
    print(f"rime-rootfs-boot: {msg}", file=sys.stderr)


def device_path(what):
    for tag, d in (("UUID=", "by-uuid"), ("LABEL=", "by-label"), ("PARTUUID=", "by-partuuid"),
                   ("PARTLABEL=", "by-partlabel")):
        if what.startswith(tag):
            return f"/dev/disk/{d}/{what[len(tag):]}"
    return what


def unit_escape(path):
    """systemd-escape --path for a /dev/disk/by-* path (the fsck unit's instance name)."""
    out = []
    for i, c in enumerate(path.strip("/")):
        if c == "/":
            out.append("-")
        elif c.isalnum() or c in ":_" or (c == "." and i > 0):
            out.append(c)
        else:
            out.append("\\x%02x" % ord(c))
    return "".join(out)


def esp_unit(head):
    what = device_path("LABEL=" + ESP_LABEL)
    fsck = f"systemd-fsck@{unit_escape(what)}.service"
    return "\n".join(head + [f"Requires={fsck}", f"After={fsck}", "", "[Mount]", f"What={what}", "Where=/boot",
                             "Type=vfat", "Options=umask=0077", ""])


def bind_unit(head):
    return "\n".join(head + [f"RequiresMountsFor={TOP}", "", "[Mount]", f"What={TOP}/boot", "Where=/boot",
                             "Type=none", "Options=bind", ""])


def unit_text(boot):
    """(unit text, required) for host.toml's [boot] table BOOT; (None, False) for no unit."""
    head = [HEADER + " from " + HOST + " [boot] (nix/modules/rootfs.nix).", "[Unit]",
            "Documentation=man:systemd.mount(5)", f"SourcePath={HOST}", "Before=local-fs.target"]
    layout = boot.get("layout")
    if layout == "bls":
        return esp_unit(head), True
    dev = boot.get("device")
    if dev is not None:
        fstype = boot.get("fstype", "auto")
        if not (isinstance(dev, str) and WHAT.fullmatch(dev) and isinstance(fstype, str) and FSTYPE.fullmatch(fstype)):
            log(f"[boot] device {dev!r} / fstype {fstype!r} is not valid; no /boot mount written")
            return None, False
        what = device_path(dev)
        fsck = f"systemd-fsck@{unit_escape(what)}.service"
        return "\n".join(head + [f"Requires={fsck}", f"After={fsck}", "", "[Mount]", f"What={what}", "Where=/boot",
                                 f"Type={fstype}", "Options=defaults", ""]), True
    if layout == "custom-cfg":
        return bind_unit(head), True
    # Nothing about this machine is known: a best guess, never one the boot waits on.
    if os.path.exists(os.path.join(BY_LABEL, ESP_LABEL)):
        log(f"[boot] layout {layout!r} names no /boot; {ESP_LABEL} is present, so /boot is that ESP (not required)")
        return esp_unit(head), False
    log(f"[boot] layout {layout!r} names no /boot and there is no {ESP_LABEL}; /boot bound from {TOP}/boot "
        "when it is a directory (not required)")
    text = bind_unit(head).replace("Before=local-fs.target", f"Before=local-fs.target\nConditionPathIsDirectory={TOP}/boot")
    return text, False


def main(argv):
    if not argv:
        log("usage: rime-rootfs-boot NORMAL [EARLY LATE]")
        return 0
    normal = argv[0]
    try:
        with open(HOST, "rb") as f:
            boot = tomllib.load(f).get("boot", {})
        if not isinstance(boot, dict):
            raise ValueError("[boot] is not a table")
    except FileNotFoundError:
        boot = {}
    except (OSError, ValueError, tomllib.TOMLDecodeError) as e:
        log(f"{HOST}: {e}; no [boot] to read")
        boot = {}
    target = os.path.join(normal, "boot.mount")
    text, required = unit_text(boot)
    if os.path.lexists(target):
        try:
            with open(target) as f:
                ours = f.readline().startswith(HEADER)
        except OSError:
            ours = False
        if not ours:
            log("boot.mount is already generated; leaving it")
            return 0
        text = None  # ours, from a run that stopped before its link: only the link is made again
    elif text is None:
        return 0
    try:
        os.makedirs(normal, exist_ok=True)
        if text is not None:
            with open(target + ".tmp", "w") as f:
                f.write(text)
            os.rename(target + ".tmp", target)
        d = os.path.join(normal, "local-fs.target." + ("requires" if required else "wants"))
        os.makedirs(d, exist_ok=True)
        if not os.path.lexists(os.path.join(d, "boot.mount")):
            os.symlink("../boot.mount", os.path.join(d, "boot.mount"))
        # systemd-gpt-auto-generator (late, lower priority than this directory) also hangs an automount with a 120 s
        # idle timeout on /boot when it sees an ESP and no fstab line. Over this mount it made /boot come and go, and
        # a private mount namespace made while it was idle saw an empty /boot (rime migrate finish refused on the
        # L16, 2026-11-13). Masked here, so /boot is this mount only.
        if not os.path.lexists(os.path.join(normal, "boot.automount")):
            os.symlink("/dev/null", os.path.join(normal, "boot.automount"))
    except OSError as e:
        log(f"could not write boot.mount: {e}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
