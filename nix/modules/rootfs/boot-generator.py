#!/usr/bin/env python3
"""rime-rootfs-boot: the systemd generator that mounts /boot on every Rime OS NixOS machine (rime.rootfs;
nix/modules/rootfs.nix). Usage: rime-rootfs-boot NORMAL [EARLY LATE].

Where /boot is is a fact about the machine, not the build: one published toplevel boots a machine moved from bootc
and a fresh install alike. Both write it into /var/lib/rime/host.toml [boot]:

  layout = "bls"                                a FRESH install (installer/rime-install-nixos.sh): Rime's own ESP,
                                                FAT labelled ESPLABEL, at /boot
  [boot] device = "UUID=..."  fstype = "ext4"   moved from bootc (`rime migrate start`), the installer's LUKS layout:
                                                /boot is its own partition
  (anything else)                               moved from bootc, the plain layout: /boot is a directory of the btrfs
                                                top level, bound from TOPMOUNT/boot (the top level is mounted there)

It writes NORMAL/boot.mount and hangs it from local-fs.target, exactly once: when another generator already wrote
boot.mount (an fstab line), that one stays. A generator never fails the boot: a host.toml it cannot read leaves the
plain layout's bind, an invalid [boot] device writes no unit, and both say why in the journal.
"""
import os
import re
import sys
import tomllib

HOST = os.environ.get("RIME_HOST_TOML", "/var/lib/rime/host.toml")
TOP = "@topMount@"
ESP_LABEL = "@espLabel@"
WHAT = re.compile(r"[^\s#]+")
FSTYPE = re.compile(r"[a-z0-9._]+")


def log(msg):
    print(f"rime-rootfs-boot: {msg}", file=sys.stderr)


def device_path(what):
    for tag, d in (("UUID=", "by-uuid"), ("LABEL=", "by-label"), ("PARTUUID=", "by-partuuid"),
                   ("PARTLABEL=", "by-partlabel")):
        if what.startswith(tag):
            return f"/dev/disk/{d}/{what[len(tag):]}"
    return what


def unit_escape(path):
    """systemd-escape --path for a /dev/disk/by-* path (the fsck unit's instance name)."""
    out = []
    for i, c in enumerate(path.strip("/")):
        if c == "/":
            out.append("-")
        elif c.isalnum() or c in ":_" or (c == "." and i > 0):
            out.append(c)
        else:
            out.append("\\x%02x" % ord(c))
    return "".join(out)


def unit_text(boot):
    head = ["# Generated by rime-rootfs-boot from " + HOST + " [boot] (nix/modules/rootfs.nix).", "[Unit]",
            "Documentation=man:systemd.mount(5)", f"SourcePath={HOST}", "Before=local-fs.target"]
    if boot.get("layout") == "bls":
        what = device_path("LABEL=" + ESP_LABEL)
        fsck = f"systemd-fsck@{unit_escape(what)}.service"
        return "\n".join(head + [f"Requires={fsck}", f"After={fsck}", "", "[Mount]", f"What={what}", "Where=/boot",
                                 "Type=vfat", "Options=umask=0077", ""])
    dev = boot.get("device")
    if dev is not None:
        fstype = boot.get("fstype", "auto")
        if not (isinstance(dev, str) and WHAT.fullmatch(dev) and isinstance(fstype, str) and FSTYPE.fullmatch(fstype)):
            log(f"[boot] device {dev!r} / fstype {fstype!r} is not valid; no /boot mount written")
            return None
        what = device_path(dev)
        fsck = f"systemd-fsck@{unit_escape(what)}.service"
        return "\n".join(head + [f"Requires={fsck}", f"After={fsck}", "", "[Mount]", f"What={what}", "Where=/boot",
                                 f"Type={fstype}", "Options=defaults", ""])
    return "\n".join(head + [f"RequiresMountsFor={TOP}", "", "[Mount]", f"What={TOP}/boot", "Where=/boot",
                             "Type=none", "Options=bind", ""])


def main(argv):
    if not argv:
        log("usage: rime-rootfs-boot NORMAL [EARLY LATE]")
        return 0
    normal = argv[0]
    try:
        with open(HOST, "rb") as f:
            boot = tomllib.load(f).get("boot", {})
        if not isinstance(boot, dict):
            raise ValueError("[boot] is not a table")
    except FileNotFoundError:
        boot = {}
    except (OSError, ValueError, tomllib.TOMLDecodeError) as e:
        log(f"{HOST}: {e}; /boot from the btrfs top level")
        boot = {}
    target = os.path.join(normal, "boot.mount")
    if os.path.lexists(target):
        log("boot.mount is already generated; leaving it")
        return 0
    text = unit_text(boot)
    if text is None:
        return 0
    try:
        os.makedirs(normal, exist_ok=True)
        with open(target + ".tmp", "w") as f:
            f.write(text)
        os.rename(target + ".tmp", target)
        d = os.path.join(normal, "local-fs.target.requires")
        os.makedirs(d, exist_ok=True)
        if not os.path.lexists(os.path.join(d, "boot.mount")):
            os.symlink("../boot.mount", os.path.join(d, "boot.mount"))
    except OSError as e:
        log(f"could not write boot.mount: {e}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
